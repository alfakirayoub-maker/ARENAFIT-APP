/** "3 سنوات", "سنتان", "11 سنة" — Arabic number/noun agreement for ages. */
function ageAr(n: number): string {
  if (n === 1) return 'سنة واحدة';
  if (n === 2) return 'سنتان';
  if (n <= 10) return `${n} سنوات`;
  return `${n} سنة`;
}

